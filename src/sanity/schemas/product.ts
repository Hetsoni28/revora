import { defineType, defineField } from 'sanity';

/** One product page. Keep every field short — the page shows it as written. */
export const product = defineType({
  name: 'product',
  title: 'Product',
  type: 'document',
  fields: [
    defineField({ name: 'name', title: 'Brand name', type: 'string', validation: (r) => r.required() }),
    defineField({
      name: 'id',
      title: 'URL slug',
      description: 'The product page and QR code use it: /products/moxora and /p/moxora. Changing it breaks printed QR codes.',
      type: 'slug',
      options: { source: 'name' },
      validation: (r) => r.required(),
    }),
    defineField({ name: 'genericName', title: 'Generic name', type: 'string', validation: (r) => r.required() }),
    defineField({
      name: 'distributed',
      title: 'Distributed by Revora',
      description: 'Turn on for brands made by another company and distributed by Revora (e.g. HYSTRIDE). Shown on the product page.',
      type: 'boolean',
      initialValue: false,
    }),
    defineField({
      name: 'category',
      title: 'Therapy area',
      type: 'reference',
      to: [{ type: 'therapyCategory' }],
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'image',
      title: 'Product photo',
      description: 'Carton and bottle, square.',
      type: 'image',
      options: { hotspot: true },
      validation: (r) => r.required(),
    }),
    defineField({
      name: 'logo',
      title: 'Brand logo',
      description: 'Transparent PNG or WebP. Shown on the homepage and product cards.',
      type: 'image',
    }),
    defineField({ name: 'badge', title: 'Type', description: 'e.g. Antibacterial + Steroid', type: 'string', validation: (r) => r.max(40) }),
    defineField({ name: 'volume', title: 'Pack size', description: 'e.g. 5 ml Sterile Dropper Vial', type: 'string', validation: (r) => r.max(50) }),
    defineField({
      name: 'summary',
      title: 'Short description',
      description: 'One line, up to 140 characters.',
      type: 'text',
      rows: 2,
      validation: (r) => r.max(140),
    }),
    defineField({
      name: 'composition',
      title: 'Composition',
      description: 'One ingredient per line, e.g. "Moxifloxacin 0.5% w/v".',
      type: 'array',
      of: [{ type: 'string' }],
    }),
    defineField({
      name: 'indications',
      title: 'Uses',
      description: 'Up to 3 short points.',
      type: 'array',
      of: [{ type: 'string' }],
      validation: (r) => r.max(3),
    }),
    defineField({ name: 'dosage', title: 'How to use', type: 'text', rows: 2, validation: (r) => r.max(160) }),
    defineField({ name: 'storage', title: 'Storage', type: 'string', validation: (r) => r.max(100) }),
    defineField({ name: 'schedule', title: 'Supply', description: 'e.g. Schedule H Prescription Drug', type: 'string' }),
    defineField({
      name: 'fssaiLicence',
      title: 'FSSAI licence number',
      description: 'Nutraceuticals only (e.g. REVOPT). Shown with the statutory “Not for medicinal use” line.',
      type: 'string',
    }),
    defineField({
      name: 'prescribingInfo',
      title: 'Prescribing information (PDF)',
      description: 'The package insert / prescribing information leaflet. Doctors open it from the product page. Upload the approved version only.',
      type: 'file',
      options: { accept: 'application/pdf' },
      fields: [
        defineField({ name: 'updated', title: 'Leaflet date', description: 'Revision date printed on the leaflet, shown next to the download.', type: 'date' }),
      ],
    }),
    defineField({ name: 'order', title: 'Order in therapy area', type: 'number' }),
    defineField({ name: 'seo', title: 'Search & sharing (SEO)', type: 'seo' }),
  ],
  preview: {
    select: {
      title: 'name',
      subtitle: 'genericName',
      media: 'image',
    },
  },
});
